import React from 'react';
import { X, Printer } from 'lucide-react';
import { StudentProfile, SimulationResult, ArticulationTarget } from '../types';
import { Scenario } from '../utils/scenario';

interface Props {
  open: boolean;
  onClose: () => void;
  profile: StudentProfile;
  target: ArticulationTarget;
  simulation: SimulationResult;
  gpa: number;
  scenario: Scenario;
}

export const ReportModal: React.FC<Props> = ({ open, onClose, profile, target, simulation, gpa, scenario }) => {
  if (!open) return null;
  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  return (
    <div className="fixed inset-0 z-[100] bg-slate-900/40 backdrop-blur-sm flex items-center justify-center p-4" onClick={onClose} role="dialog" aria-modal="true">
      <div className="w-full max-w-2xl max-h-[90vh] flex flex-col rounded-2xl border border-slate-300 bg-white shadow-xl" onClick={e => e.stopPropagation()}>
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-200">
          <h2 className="text-lg font-bold">Counselor-ready plan</h2>
          <div className="flex items-center gap-2">
            <button onClick={() => window.print()} className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-blue-600 hover:bg-blue-700 text-white text-sm font-semibold">
              <Printer className="w-4 h-4" /> Print / Save PDF
            </button>
            <button onClick={onClose} className="p-1 text-slate-500 hover:text-slate-900" aria-label="Close"><X className="w-5 h-5" /></button>
          </div>
        </div>
        <div className="overflow-y-auto scroll-thin">
          <div id="print-area" className="p-6 bg-white text-slate-900 text-sm">
            <div className="flex justify-between items-start border-b-2 border-orange-500 pb-3">
              <div>
                <div className="text-xl font-extrabold">HawkPath Transfer Plan</div>
                <div className="text-xs text-slate-600">Bring this to your MESA or transfer counselor appointment</div>
              </div>
              <div className="text-right text-xs text-slate-600">{today}</div>
            </div>
            <div className="grid grid-cols-2 gap-x-6 gap-y-1 mt-4 text-[13px]">
              <div><b>Student:</b> {profile.name}{profile.isMesaStudent ? ' (MESA)' : ''}</div>
              <div><b>Goal:</b> {target.universityName}, {target.majorName}</div>
              <div><b>Current GPA (planner calc):</b> {gpa.toFixed(2)}</div>
              <div><b>Min / competitive GPA:</b> {target.minTransferGPA} / {target.competitiveGPA}</div>
              <div><b>Work:</b> {scenario.workHours ?? profile.workingHoursPerWeek} h/week</div>
              <div><b>Projected transfer:</b> {simulation.graduationTerm}</div>
            </div>
            {scenario.label && <p className="mt-3 text-[12px] bg-orange-50 border border-orange-200 rounded p-2"><b>Scenario:</b> {scenario.label}</p>}
            <h3 className="mt-5 font-bold">Critical prerequisite path</h3>
            <p className="font-mono text-[12px]">{simulation.criticalPathCourses.join('  →  ')}</p>
            <h3 className="mt-5 font-bold">Term-by-term plan</h3>
            <table className="w-full mt-2 text-[12px] border-collapse">
              <thead><tr className="bg-slate-100"><th className="text-left p-1.5 border">Term</th><th className="text-left p-1.5 border">Courses</th><th className="text-right p-1.5 border">Units</th></tr></thead>
              <tbody>
                {simulation.semesters.map(s => (
                  <tr key={s.id}>
                    <td className="p-1.5 border whitespace-nowrap">{s.term} {s.year}</td>
                    <td className="p-1.5 border">{s.courses.map(c => `${c.code} (${c.title})`).join('; ')}</td>
                    <td className="p-1.5 border text-right">{s.totalUnits}</td>
                  </tr>
                ))}
              </tbody>
            </table>
            <h3 className="mt-5 font-bold">Notes</h3>
            <ul className="list-disc ml-5 text-[12px] space-y-0.5">
              <li>{simulation.counselorRecommendation}</li>
              <li>{target.notes}</li>
              {simulation.bottlenecksFound.map(b => <li key={b}>{b}</li>)}
            </ul>
            <p className="mt-6 text-[10.5px] text-slate-500 border-t pt-2">
              Planning aid only, not an official degree audit. Verify articulation on ASSIST.org and with a counselor. Generated by HawkPath AI.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
};
